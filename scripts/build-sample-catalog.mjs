// Turns Strudel's drum map and gm.mjs into the name catalog the UI and the packer share.
import { readFileSync, writeFileSync } from "node:fs";

const drums = JSON.parse(readFileSync("assets/samples/tidal-drum-machines.json", "utf8"));
const gmSource = readFileSync("assets/samples/gm.mjs", "utf8");

const KICK = new Set(["bd"]);
const SNARE = new Set(["sd", "rim", "cp"]);
const HAT = new Set(["hh", "oh", "cr", "rd"]);
const VENDORS = [
  "SequentialCircuits",
  "Soundmasters",
  "Roland",
  "Yamaha",
  "Oberheim",
  "Simmons",
  "Alesis",
  "Casio",
  "Akai",
  "Boss",
  "Korg",
  "Emu",
  "Linn",
  "Moog",
  "Rhodes",
  "Univox",
  "Doepfer",
  "Serge",
  "Visco",
  "Sakata",
  "RhythmAce",
  "Xdrum",
  "MFB",
];

function drumLabel(machine) {
  let rest = machine;
  for (const vendor of VENDORS) {
    if (machine.startsWith(vendor) && machine.length > vendor.length) {
      rest = machine.slice(vendor.length);
      break;
    }
  }
  return rest.slice(0, 8).toUpperCase();
}

function laneOf(suffix) {
  if (KICK.has(suffix)) return "kick";
  if (SNARE.has(suffix)) return "snare";
  if (HAT.has(suffix)) return "hat";
  return "perc";
}

const lanes = { kick: [], snare: [], hat: [], perc: [] };
for (const [key, files] of Object.entries(drums)) {
  if (key.startsWith("_") || !Array.isArray(files)) continue;
  const cut = key.lastIndexOf("_");
  if (cut < 1) continue;
  const name = drumLabel(key.slice(0, cut));
  const lane = laneOf(key.slice(cut + 1));
  files.forEach((file, take) => {
    if (typeof file === "string") lanes[lane].push({ name, take, file });
  });
}

const gm = [];
let key = null;
let take = 0;
for (const line of gmSource.split(/\n/)) {
  const named = line.match(/^\s*(gm_[a-z0-9_]+)\s*:/);
  if (named) {
    key = named[1];
    take = 0;
    continue;
  }
  if (!key || line.trim().startsWith("//")) continue;
  for (const hit of line.matchAll(/'([0-9]{4}_[A-Za-z0-9_]+)'/g)) {
    const at = line.indexOf(`'${hit[1]}'`);
    const comment = line.indexOf("//");
    if (comment >= 0 && comment < at) continue;
    const name = key.replace(/^gm_/, "").replace(/_/g, " ").toUpperCase();
    gm.push({ name, take, file: hit[1] });
    take += 1;
  }
}

const base = typeof drums._base === "string" ? drums._base : "";
const body = `// Generated by scripts/build-sample-catalog.mjs. Do not edit.
export interface SampleName {
  name: string;
  take: number;
  file: string;
}

export const DRUM_BASE = ${JSON.stringify(base)};
export const GM_BASE = "https://felixroos.github.io/webaudiofontdata/sound/";

export const KICK_SAMPLES: SampleName[] = ${JSON.stringify(lanes.kick)};
export const SNARE_SAMPLES: SampleName[] = ${JSON.stringify(lanes.snare)};
export const HAT_SAMPLES: SampleName[] = ${JSON.stringify(lanes.hat)};
export const PERC_SAMPLES: SampleName[] = ${JSON.stringify(lanes.perc)};
export const GM_SAMPLES: SampleName[] = ${JSON.stringify(gm)};
`;

writeFileSync("src/core/sample-catalog.ts", body);
console.log(
  `kick ${lanes.kick.length} snare ${lanes.snare.length} hat ${lanes.hat.length} perc ${lanes.perc.length} gm ${gm.length}`,
);
